import { mkdir, readFile, writeFile } from "node:fs/promises";
const root = new URL("../", import.meta.url);
const files = ["schemas.js", "state.js", "tracker.js", "backend.js"];
const parts = [];
for (const file of files) parts.push((await readFile(new URL(`src/${file}`, root), "utf8")).replace(/^import\s*\{[\s\S]*?\}\s*from\s*["'][^"']+["'];\s*/gm, "").replace(/^export[ \t]+/gm, ""));
await mkdir(new URL("dist/", root), { recursive: true });
await writeFile(new URL("dist/backend.js", root), `// Story Continuity Engine 1.0.0 — generated by scripts/build.mjs\n${parts.join("\n\n")}`);
await writeFile(new URL("dist/frontend.js", root), `// Story Continuity Engine 1.0.0 — generated by scripts/build.mjs\n${await readFile(new URL("src/frontend.js", root), "utf8")}`);
console.log("Built Story Continuity Engine.");
